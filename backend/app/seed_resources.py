def seed_academic_resources(db: Session):
    """Inserts baseline catalog resources if they don't already exist."""
    existing_count = db.query(AcademicResource).count()
    if existing_count > 0:
        return

    for item in ACADEMIC_RESOURCES_DATA:
        res = AcademicResource(
            id=item["id"],
            title=item["title"],
            description=item.get("description", ""),
            subject_code=item["subject_code"],
            subject_name=item["subject_name"],
            topic=item.get("topic", ""),
            syllabus_unit=item.get("syllabus_unit", ""),
            resource_type=item["resource_type"],
            source_category=item.get("source_category", "curated"),
            provenance=item.get("provenance", "Curated Academic"),
            institution_or_publisher=item.get("institution_or_publisher", ""),
            url=item["url"],
            language=item.get("language", "English"),
            semester=item.get("semester", ""),
            curriculum=item.get("curriculum", "All"),
            is_verified=item.get("is_verified", True),
            rating=item.get("rating", 4.8),
        )
        db.add(res)
    db.commit()
